  const PATS = [
    [/^ứng dụng (.+)$/, m => `the ${m[1]} app`],
    [/^Miễn phí · phiên bản (.+?) · (.+)$/, m => `Free · version ${m[1]} · ${m[2]}`],
    [/^(Tải IPA cho iPhone|Tải APK cho Android) · (.+)$/, m => `${EN[m[1]]} · ${m[2]}`],
    [/^Dẫn đường tới (.+)$/, m => `Navigating to ${tr(m[1])}`],
    [/^Âm lượng (\d+)%$/, m => `Volume ${m[1]}%`],
    [/^Xoá toàn bộ thông báo \((\d+)\)$/, m => `Clear all notifications (${m[1]})`],
  ];
  const norm = s => s.replace(/\s+/g, " ").trim();
  function tr(s) {
    const k = norm(s);
    if (!k) return s;
    let t = EN[k];
    if (t === undefined) for (const [rx, f] of PATS) { const m = k.match(rx); if (m) { t = f(m); break; } }
    if (t === undefined) return s;
    return (/^\s/.test(s) ? " " : "") + t + (/\s$/.test(s) ? " " : "");
  }

  const KEY = "nc-lang";
  const ATTRS = ["alt", "title", "placeholder", "aria-label"];
  const done = new Map(); // text node -> [vi, en]
  let lang = "vi";

  function textNode(n) {
    const p = n.parentNode;
    if (!p || /^(SCRIPT|STYLE)$/.test(p.nodeName)) return;
    const rec = done.get(n);
    if (rec && n.data === rec[1]) return;
    const en = tr(n.data);
    if (en !== n.data) { done.set(n, [n.data, en]); n.data = en; }
  }
  function element(el) {
    for (const a of ATTRS) {
      const v = el.getAttribute(a);
      if (!v) continue;
      const vi = el.getAttribute("data-vi-" + a) ?? v;
      const en = tr(vi);
      if (en !== vi) { el.setAttribute("data-vi-" + a, vi); el.setAttribute(a, en); }
    }
  }
  function walk(root) {
    if (root.nodeType === 3) return textNode(root);
    if (root.nodeType !== 1) return;
    element(root);
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    for (let n = w.nextNode(); n; n = w.nextNode()) n.nodeType === 3 ? textNode(n) : element(n);
  }
  const mo = new MutationObserver(ms => {
    if (lang !== "en") return;
    for (const m of ms) {
      if (m.type === "characterData") textNode(m.target);
      else m.addedNodes.forEach(walk);
    }
  });

  const metas = [...document.querySelectorAll('meta[name="description"], meta[property^="og:"], meta[name^="twitter:"]')];
  function apply(l) {
    lang = l;
    document.documentElement.lang = l;
    if (l === "en") {
      walk(document.body);
      for (const m of metas) { const vi = m.dataset.vi ?? m.content; const en = tr(vi); if (en !== vi) { m.dataset.vi = vi; m.content = en; } }
      if (!document.documentElement.dataset.ncTitle) document.documentElement.dataset.ncTitle = document.title;
      document.title = tr(document.documentElement.dataset.ncTitle);
      mo.observe(document.body, { subtree: true, childList: true, characterData: true });
    } else {
      mo.disconnect();
      for (const [n, [vi, en]] of done) if (n.data === en) n.data = vi;
      done.clear();
      document.querySelectorAll("*").forEach(el => { for (const a of ATTRS) { const vi = el.getAttribute("data-vi-" + a); if (vi !== null) { el.setAttribute(a, vi); el.removeAttribute("data-vi-" + a); } } });
      for (const m of metas) if (m.dataset.vi) m.content = m.dataset.vi;
      if (document.documentElement.dataset.ncTitle) document.title = document.documentElement.dataset.ncTitle;
    }
    const b = document.getElementById("langBtn");
    if (b) { b.textContent = l === "en" ? "VI" : "EN"; b.title = l === "en" ? "Tiếng Việt" : "English"; b.setAttribute("aria-label", b.title); }
  }

  let pick = new URLSearchParams(location.search).get("lang");
  if (pick !== "en" && pick !== "vi") { try { pick = localStorage.getItem(KEY); } catch (_) { pick = null; } }
  apply(pick === "en" ? "en" : "vi");
  document.getElementById("langBtn")?.addEventListener("click", () => {
    const l = lang === "en" ? "vi" : "en";
    try { localStorage.setItem(KEY, l); } catch (_) {}
    apply(l);
  });
